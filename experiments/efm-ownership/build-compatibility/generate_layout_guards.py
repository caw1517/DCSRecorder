"""Generate fail-closed read-only diagnostic guards from the audited inventory."""
import json
from audit import HERE, guards

profile=json.loads((HERE/'candidate_profile.json').read_text())
names={'dcs':'nullptr','aifm':'L"AIFM.dll"','worldgeneral':'L"WorldGeneral.dll"','sound':'L"Sound.dll"'}
lines=['// Generated by generate_layout_guards.py; read-only diagnostic only.',
       '#pragma once','#include "../native_identity.h"','#include <array>','#include <filesystem>',
       'namespace layout_guards {',
       'template<size_t N> inline bool matches(const wchar_t* module,uintptr_t rva,const std::array<unsigned char,N>& bytes) {',
       '    auto base=reinterpret_cast<uintptr_t>(GetModuleHandleW(module));std::array<unsigned char,N> actual{};',
       '    return base && native_identity::read(base+rva,actual) && actual==bytes;',
       '}',
       'inline bool valid() {',
       '    wchar_t host[32768]{};',
       '    if(!GetModuleFileNameW(nullptr,host,32768) || _wcsicmp(std::filesystem::path(host).filename().c_str(),L"DCS.exe"))return false;',
       '    return']
for index,(source,module,old,signature) in enumerate(guards()):
    rva=profile.get(module,{}).get(hex(old),hex(old))
    code=bytes.fromhex(profile['changed_signatures'].get(f'{module}:{hex(old)}',signature))
    lines.append('        '+('' if index==0 else '&& ')+f'matches({names[module]},{rva},std::array<unsigned char,{len(code)}>{{'+','.join(hex(v) for v in code)+'})')
lines+=['        ;','}','}']
(HERE/'layout_guards.h').write_text('\n'.join(lines)+'\n')
