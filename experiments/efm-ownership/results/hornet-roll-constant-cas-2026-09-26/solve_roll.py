"""Offline geometric roll study; stdlib only. Not an aircraft flight model."""
import math
import json
from pathlib import Path

G=9.80665
RAD=math.pi/180
def smooth(u):
    u=max(0,min(1,u)); return u*u*u*(10+u*(-15+6*u))

def speed(h):
    # 400 KCAS in ISA; same calibrated/indicated approximation as earlier tests.
    t=288.15-0.0065*h
    p=101325*(t/288.15)**(G/(287.05287*0.0065))
    vc=400*1852/3600
    qc=101325*((1+vc*vc/(5*1.4*287.05287*288.15))**3.5-1)
    return math.sqrt(1.4*287.05287*t*5*((1+qc/p)**(2/7)-1))

def bank(t,a,b,c=6):
    # Monotone cubic Hermite interpolation, zero roll rate at both ends.
    lengths=[a,b,c]; angles=[0,60*RAD,300*RAD,360*RAD]
    slopes=[(angles[i+1]-angles[i])/lengths[i] for i in range(3)]
    rates=[0]
    for i in range(2):
        w1=2*lengths[i+1]+lengths[i];w2=lengths[i+1]+2*lengths[i]
        rates.append((w1+w2)/(w1/slopes[i]+w2/slopes[i+1]))
    rates.append(0)
    i=0
    while i<2 and t>lengths[i]: t-=lengths[i];i+=1
    u=max(0,min(1,t/lengths[i]));h=lengths[i]
    return -((2*u**3-3*u*u+1)*angles[i]+(u**3-2*u*u+u)*h*rates[i]+(-2*u**3+3*u*u)*angles[i+1]+(u**3-u*u)*h*rates[i+1])

def derivative(t,y,phi,n):
    pitch,heading,x,h,z=y;v=speed(h)
    return [G/v*(n*math.cos(phi)-math.cos(pitch)),G*n*math.sin(phi)/(v*math.cos(pitch)),v*math.cos(pitch)*math.cos(heading),v*math.sin(pitch),v*math.cos(pitch)*math.sin(heading)]

def rk4(t,y,dt,control):
    def f(t,y): return derivative(t,y,*control(t))
    k1=f(t,y);k2=f(t+dt/2,[v+dt*k/2 for v,k in zip(y,k1)])
    k3=f(t+dt/2,[v+dt*k/2 for v,k in zip(y,k2)]);k4=f(t+dt,[v+dt*k for v,k in zip(y,k3)])
    return [v+dt*(a+2*b+2*c+d)/6 for v,a,b,c,d in zip(y,k1,k2,k3,k4)]

def pull():
    y=[0,0,0,2000,0];t=0
    control=lambda t:(0,1+0.8*smooth(t/4))
    while y[0]<14*RAD:
        nxt=rk4(t,y,0.01,control)
        if nxt[0]>=14*RAD:
            dt=0.01*(14*RAD-y[0])/(nxt[0]-y[0]);y=rk4(t,y,dt,control);t+=dt;break
        y=nxt;t+=0.01
    return t,y

PULL_TIME,ENTRY=pull()
def simulate(a,b,dt=0.025,collect=False):
    y=ENTRY[:];t=0;peak=y[0];low=y[0];rows=[]
    end=a+b+6
    def control(t): return bank(t,a,b),1.8-0.8*smooth((t-a-b)/6)
    while t<end-1e-9:
        step=min(dt,end-t);y=rk4(t,y,step,control);t+=step
        peak=max(peak,y[0]);low=min(low,y[0])
        if collect: rows.append([t,*y,*control(t)])
    return peak/RAD,y[0]/RAD,low/RAD,y,rows

def solve():
    a,b=12.0,12.0
    for iteration in range(15):
        r=simulate(a,b);f=[r[0]-30,r[1]]
        print(iteration,a,b,'peak/end/min',r[:3])
        if max(map(abs,f))<1e-5: break
        eps=0.01;ra=simulate(a+eps,b);rb=simulate(a,b+eps)
        j00=(ra[0]-r[0])/eps;j10=(ra[1]-r[1])/eps;j01=(rb[0]-r[0])/eps;j11=(rb[1]-r[1])/eps
        det=j00*j11-j01*j10
        da=(-f[0]*j11+j01*f[1])/det;db=(j10*f[0]-j00*f[1])/det
        scale=min(1,3/max(abs(da),abs(db)))
        a+=scale*da;b+=scale*db
        assert a>1 and b>1
    return a,b

if __name__=='__main__':
    a,b=solve();peak,end,low,y,rows=simulate(a,b,0.005,True)
    report={'pull_seconds':PULL_TIME,'entry_seconds':a,'middle_seconds':b,'recovery_seconds':6,'peak_pitch_degrees':peak,'end_pitch_degrees':end,'min_pitch_degrees':low,'entry_altitude':ENTRY[3],'end_altitude':y[3],'end_heading_degrees':y[1]/RAD,'max_speed':max(speed(row[4]) for row in rows)}
    output=Path(__file__).parent/'package/hornet-roll';output.mkdir(parents=True,exist_ok=True)
    (output/'geometry.json').write_text(json.dumps(report,indent=2)+'\n')
    # Bake the reference trajectory at 50 Hz. Position interpolation in C++
    # uses endpoint velocities; attitude is reconstructed from continuous angles.
    total=PULL_TIME+a+b+6
    def control(t):
        if t<=PULL_TIME: return 0,1+0.8*smooth(t/4)
        r=t-PULL_TIME
        return bank(r,a,b),1.8-0.8*smooth((r-a-b)/6)
    t=0;y=[0,0,0,2000,0];samples=[]
    while True:
        phi,n=control(t)
        samples.append([t,*y,phi,n])
        if t>=total: break
        step=min(0.02,total-t);y=rk4(t,y,step,control);t+=step
    header=['// Generated by solve_roll.py. Reference atmosphere: ISA, 400 KCAS, 2000 m start.',
            '#pragma once','#include <array>','namespace hornet_roll_data {',
            'struct Sample { double t,pitch,heading,x,height,z,bank,load; };',
            f'constexpr double pull_duration={PULL_TIME:.15g}, entry_duration={a:.15g}, middle_duration={b:.15g}, recovery_duration=6;',
            f'constexpr double maneuver_duration={total:.15g};',
            f'inline constexpr std::array<Sample,{len(samples)}> samples={{{{']
    header+=['    {'+','.join(f'{v:.15g}' for v in row)+'},' for row in samples]
    header+=['}};','}']
    (Path(__file__).parent/'hornet_roll_data.h').write_text('\n'.join(header)+'\n')
    print(json.dumps(report,indent=2))
